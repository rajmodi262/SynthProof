"""Regenerates every published number and emits a manifest that pins it.

WHAT THIS BUYS. The thesis can state "every number in this document was regenerated by commit
X under manifest hash Y" — a claim very few undergraduate theses can make, and one a reviewer
can check. It also catches the failure mode where a result file drifts from the code that
supposedly produced it, which is otherwise invisible until someone tries to rerun an
experiment months later.

WHAT THE MANIFEST COVERS. The commit, whether the tree was dirty, the interpreter and platform,
resolved versions of every dependency that affects a number, the dataset checksums, the seeds
and grids each experiment used, and a SHA-256 over each result file plus one over all of them
together. Two runs that agree on the manifest hash produced identical results.

WHAT IT DOES NOT COVER, stated so nobody over-reads it: floating-point results can differ
across BLAS builds and CPU architectures even at a fixed seed. A manifest mismatch means
"something changed", not necessarily "someone edited a number".

AND `--run` DOES NOT RECOMPUTE H1. `run_h1` is resumable by design -- `frontier/checkpoint.py`
exists because the 75-cell grid was lost twice mid-run -- so it reloads `results/h1_cells/` and
re-aggregates rather than re-fitting. The tell is `elapsed_seconds`: H1 reports ~0.7s where H2,
H3 and fairness report 20-70s. Those three genuinely re-run. To force H1 to recompute, delete
`results/h1_cells/` first, and expect roughly four hours per dataset. Verified 2026-08-23: a
`--update` pass reproduced every committed number exactly, with only timing metadata changing --
which is a real reproducibility result for H2/H3/fairness and a checkpoint-integrity result for
H1, and those are different claims.

Usage:
    python -m scripts.reproduce              # verify against the committed manifest
    python -m scripts.reproduce --run        # re-run every experiment first (long)
    python -m scripts.reproduce --update     # re-run and rewrite the manifest
"""

