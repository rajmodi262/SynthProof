"""Cross-dataset comparison of the H1 grid: UCI Adult against ACSIncome.

This is what removes preregistration deviation D1 ("ACSIncome not run; any H1 conclusion is
single-dataset"). The question it answers is narrow and stated in advance:

    Does the mechanism ORDERING established on Adult reproduce on ACSIncome?

Ordering, not magnitude. Absolute correlation error is not comparable across datasets — the
two tables have different true correlations (Adult 0.1034, ACS 0.0721), so a mechanism that
reproduces structure equally well on both would still post different errors. The rank of the
mechanisms is the claim that transfers.

READ-ONLY. This script runs no experiment and writes no result file; it reads two committed
JSONs and renders them. If the orderings disagree, it says so plainly. Per standing rule 5
a disagreement is a finding about external validity, not a bug to be tuned away.
"""

import argparse
import json
from pathlib import Path

ADULT = "results/h1_all_families.json"
ACS = "results/acs/h1_all_families.json"

# Lower is better for correlation error, higher is better for TSTR F1.
METRICS = {"correlation_error": "lower", "tstr_f1": "higher"}


def load(path):
    p = Path(path)
    if not p.exists():
        raise SystemExit(f"{path} not found. Run `make h1` (Adult) and `make h1-acs` (ACS) first.")
    return json.loads(p.read_text(encoding="utf-8"))


def label(payload, fallback):
    """The Adult file predates the --dataset flag and carries no label."""
    return payload.get("dataset_label") or payload.get("dataset") or fallback


def cell(payload, mech, eps):
    for c in payload["cells"]:
        if c["mechanism"] == mech and abs(c["target_eps"] - eps) < 1e-9:
            return c
    return None


def separated(a, b):
    """True when two bootstrap CIs do not overlap."""
    return a["hi"] < b["lo"] or b["hi"] < a["lo"]


def ranking(payload, eps, metric):
    """Mechanisms best-to-worst at one epsilon, with each one's CI."""
    rows = [(m, cell(payload, m, eps)) for m in payload["mechanisms"]]
    rows = [(m, c[metric]) for m, c in rows if c is not None]
    return sorted(rows, key=lambda r: r[1]["mean"], reverse=METRICS[metric] == "higher")


def render_metric(adult, acs, metric, eps_grid, out):
    out.append(f"\n### {metric} ({METRICS[metric]} is better)\n")
    out.append("| mechanism | eps | Adult mean [95% CI] | ACS mean [95% CI] |")
    out.append("|---|---:|---|---|")
    mechs = [m for m in adult["mechanisms"] if m in acs["mechanisms"]]
    for mech in mechs:
        for eps in eps_grid:
            ca, cb = cell(adult, mech, eps), cell(acs, mech, eps)
            if ca is None or cb is None:
                continue
            a, b = ca[metric], cb[metric]
            out.append(
                f"| {mech} | {eps:g} | {a['mean']:.4f} [{a['lo']:.4f}, {a['hi']:.4f}] "
                f"| {b['mean']:.4f} [{b['lo']:.4f}, {b['hi']:.4f}] |"
            )


def render_ordering(adult, acs, metric, eps, out):
    """The claim that is supposed to transfer, and whether it does."""
    ra, rb = ranking(adult, eps, metric), ranking(acs, eps, metric)
    out.append(f"\n### Mechanism ordering at eps={eps:g}, by {metric}\n")
    out.append(f"- **Adult:** {' > '.join(m for m, _ in ra)}")
    out.append(f"- **ACS:**   {' > '.join(m for m, _ in rb)}")

    agree = [m for m, _ in ra] == [m for m, _ in rb]
    out.append("")
    if agree:
        out.append(
            "The ordering **reproduces**. The ranking is a property of the mechanisms, "
            "not of UCI Adult."
        )
    else:
        out.append(
            "> **The orderings DISAGREE.** This is reported as measured. It means the "
            "Adult ranking is not, on this evidence, dataset-independent, and any claim "
            "resting on it must be stated as Adult-specific."
        )

    # An ordering is only meaningful where the intervals actually separate.
    out.append("\nAdjacent-pair CI separation:\n")
    out.append("| dataset | pair | separated? |")
    out.append("|---|---|---|")
    for name, rank in (("Adult", ra), ("ACS", rb)):
        for (m1, s1), (m2, s2) in zip(rank, rank[1:], strict=False):
            out.append(
                f"| {name} | {m1} vs {m2} | "
                f"{'yes' if separated(s1, s2) else 'NO — indistinguishable'} |"
            )


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--adult", default=ADULT)
    ap.add_argument("--acs", default=ACS)
    ap.add_argument("--out", default="results/acs/CROSS_DATASET.md")
    args = ap.parse_args()

    adult, acs = load(args.adult), load(args.acs)
    eps_grid = [e for e in adult["eps_grid"] if e in acs["eps_grid"]]
    top_eps = max(eps_grid)

    out = ["# Cross-dataset comparison: UCI Adult vs ACSIncome", ""]
    out.append(
        "Generated by `scripts/compare_datasets.py` from committed result files. "
        "It runs no experiment."
    )
    out.append("\n## Protocol\n")
    out.append("| | Adult | ACS |")
    out.append("|---|---|---|")
    out.append(f"| label | {label(adult, 'UCI Adult')} | {label(acs, 'ACSIncome')} |")
    out.append(f"| rows | {adult['n_rows']} | {acs['n_rows']} |")
    out.append(f"| seeds | {len(adult['seeds'])} | {len(acs['seeds'])} |")
    out.append(
        f"| structure pair | {'x'.join(adult.get('corr_cols', ['age', 'hours_per_week']))} "
        f"| {'x'.join(acs.get('corr_cols', []))} |"
    )
    out.append(
        f"| true correlation | {adult['true_correlation']:.4f} "
        f"| {acs['true_correlation']:.4f} |"
    )
    out.append(
        "\nThe two true correlations differ, so **absolute** correlation error is not "
        "comparable between the datasets. Only the mechanism ordering is."
    )

    for metric in METRICS:
        render_ordering(adult, acs, metric, top_eps, out)
    for metric in METRICS:
        render_metric(adult, acs, metric, eps_grid, out)

    text = "\n".join(out) + "\n"
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text(text, encoding="utf-8")
    print(text)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
