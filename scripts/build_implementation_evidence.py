        "| Discrete Gaussian by rejection sampling, CKS'20 §5.2 Alg. 1 | "
        "`accounting/noise.py::_discrete_gaussian_single` |",
        "| Discrete Laplace as a two-sided geometric | Ghosh, Roughgarden & Sundararajan (2012) |",
