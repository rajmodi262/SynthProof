"""Generates the evidence map for Chapter 5 (Implementation).

WHAT THIS IS AND IS NOT. Chapter 5 describes what was built. Most of its raw material already
exists as module docstrings, defect records and test names -- it is scattered, not missing. This
script gathers it into one place, per section, with live counts and a file:line pointer for
every claim, so writing the chapter is a matter of argument rather than archaeology.

It emits **no prose**. Each section gets its evidence and a `[WRITE: ...]` marker. An unwritten
paragraph stays visibly unwritten.

Counts are read from the tree and from `results/MANIFEST.json` at build time, never typed, and
never defaulted -- `table_h2` in the sibling script once emitted a whole table of zeros from
`.get(key, 0)`, and a chapter that miscounts its own tests is the same defect wearing a
different hat.

Run from the repository root:

    python scripts/build_implementation_evidence.py
"""

from __future__ import annotations

import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "thesis" / "ch05-evidence.md"


def loc(rel: str) -> int:
    return len((ROOT / rel).read_text(encoding="utf-8").split("\n"))


def package_loc() -> int:
    return sum(loc(str(p.relative_to(ROOT))) for p in (ROOT / "synthproof").rglob("*.py"))


def count_tests() -> tuple[int, int]:
    """(test functions, test files). Parsed, not grepped -- a commented-out def is not a test."""
    files = sorted((ROOT / "tests").glob("test_*.py"))
    n = 0
    for f in files:
        for node in ast.walk(ast.parse(f.read_text(encoding="utf-8"))):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith(
                "test_"
            ):
                n += 1
    return n, len(files)


def module_table() -> str:
    """5.2 -- module boundaries match the pipeline stages in Ch.4."""
    rows = [
        "| Package | Lines | Responsibility | Read first |",
        "|---|---:|---|---|",
    ]
    spec = [
        ("accounting/", "Composition, calibration, discrete noise, the second accountant",
         "`accounting/differential.py`"),
        ("data/", "Public schema, DP domain profiler, the refusal gate, dataset loaders",
         "`data/preflight.py`"),
        ("generators/", "independent · pairwise · aim (private-PGM) · copula · leaky (control)",
         "`generators/aim.py`"),
        ("audit/", "Paired and one-run auditors, subgroup audit, detection floor, TOST",
         "`audit/steinke.py`"),
        ("attacks/", "Distance MIA, exact-match singling out, DOMIAS, attribute inference",
         "`attacks/attribute_inference.py`"),
        ("evaluate/", "TSTR / TRTR on a shared held-out split", "`evaluate/utility.py`"),
        ("ledger/", "Hash-chained Ed25519 ledger, signed head, allocator, sheet signing",
         "`ledger/types.py`"),
        ("frontier/", "Experiment runner, checkpointing, Privacy Data Sheet export",
         "`frontier/experiment.py`"),
        ("api/", "FastAPI service backing the console", "`api/main.py`"),
    ]
    for pkg, what, first in spec:
        pkg_dir = ROOT / "synthproof" / pkg.rstrip("/")
        n = sum(loc(str(q.relative_to(ROOT))) for q in pkg_dir.rglob("*.py"))
        rows.append(f"| `synthproof/{pkg}` | {n:,} | {what} | {first} |")
    return "\n".join(rows)


def main() -> None:
    manifest = json.loads((ROOT / "results" / "MANIFEST.json").read_text(encoding="utf-8"))
    deps = manifest["dependencies"]
    env = manifest["environment"]
    n_tests, n_files = count_tests()

